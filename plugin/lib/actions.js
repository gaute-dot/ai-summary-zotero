/* global Zotero, Services, AISummary */
"use strict";

AISummary.Actions = {
  /** Map the current selection to regular (parent) items, without duplicates. */
  targetItems(win) {
    const selected = win.ZoteroPane.getSelectedItems();
    const out = new Map();
    let skipped = 0;
    for (const item of selected) {
      let target = null;
      if (item.isRegularItem()) target = item;
      else if ((item.isAttachment() || item.isNote()) && item.parentItem) target = item.parentItem;
      if (target) out.set(target.id, target);
      else skipped++;
    }
    return { items: [...out.values()], skipped };
  },

  /**
   * Decide what to do with an existing note of the same title.
   * Returns "replace" | "new" | "skip". `state.remembered` stores "apply to all".
   */
  resolveDuplicate(win, settings, title, item, state) {
    if (settings.duplicateMode !== "ask") return settings.duplicateMode;
    if (state.remembered) return state.remembered;
    const ps = Services.prompt;
    const flags = ps.BUTTON_POS_0 * ps.BUTTON_TITLE_IS_STRING
      + ps.BUTTON_POS_1 * ps.BUTTON_TITLE_IS_STRING
      + ps.BUTTON_POS_2 * ps.BUTTON_TITLE_IS_STRING;
    const check = { value: false };
    const name = item.getField("title") || "this item";
    const choice = ps.confirmEx(
      win, "AI Summary",
      "“" + name + "” already has a note called “" + title + "”.\n\nWhat should happen?",
      flags, "Replace it", "Skip", "Add another note",
      state.total > 1 ? "Do the same for the remaining items" : null, check
    );
    const action = choice === 0 ? "replace" : choice === 2 ? "new" : "skip";
    if (check.value) state.remembered = action;
    return action;
  },

  /** Generate one note for one item. Returns "created" | "replaced" | "skipped". */
  async processItem(win, item, job, state) {
    const settings = job.settings;
    const provider = settings.provider;
    const model = AISummary.getModel(provider);
    const title = job.question ? AISummary.Notes.qaTitle(job.question) : AISummary.Notes.summaryTitle(job.preset);

    let existing = null;
    if (!job.question) {
      existing = AISummary.Notes.findByTitle(item, title);
      if (existing) {
        const action = this.resolveDuplicate(win, settings, title, item, state);
        if (action === "skip") return "skipped";
        if (action === "new") existing = null;
      }
    }

    const ctx = await AISummary.Context.collect(item, settings, provider);
    const preset = job.question ? { id: "qa", name: "Question", prompt: AISummary.QA_PROMPT } : job.preset;
    const prompt = AISummary.buildPrompt(ctx, preset, settings, { question: job.question || "" });

    const result = await AISummary.Providers.generate(provider, {
      model,
      apiKey: AISummary.getApiKey(provider),
      system: prompt.system,
      user: prompt.user,
      pdf: ctx.pdf,
      maxTokens: settings.maxTokens,
      temperature: provider === "anthropic" ? null : settings.temperature,
      effort: provider === "anthropic" ? settings.anthropicEffort || null : null
    });
    if (!result.text.trim()) throw new Error("The model returned an empty answer.");

    const remarks = ctx.notes.slice();
    if (result.truncated) remarks.push("the answer hit the output token limit and may be cut off (raise “Max output tokens”)");
    let footer = "";
    if (settings.addFooter) {
      footer = "Generated by " + AISummary.PROVIDER_LABELS[provider] + " (" + model + ") on "
        + new Date().toLocaleString() + " · "
        + (job.question ? "Q&A" : "preset: " + job.preset.name) + " · input: " + ctx.source
        + (remarks.length ? " · Note: " + remarks.join("; ") : "")
        + ". AI-generated – verify against the article.";
    }

    const html = AISummary.Notes.buildHTML({
      title,
      markdown: result.text,
      citations: result.citations,
      footer,
      question: job.question
    });
    await AISummary.Notes.save({
      parent: item,
      existing,
      html,
      tags: AISummary.Notes.tagsFor(settings, provider, model)
    });
    return existing ? "replaced" : "created";
  },

  progressLine(pw, item) {
    const text = item.getField("title") || "(untitled)";
    try {
      return new pw.ItemProgress(item.itemType, text);
    } catch (e) {
      return new pw.ItemProgress(null, text);
    }
  },

  /** Run a job over all selected items with a progress window. */
  async run(win, job) {
    if (AISummary.batch.running) {
      AISummary.alert(win, "A summary job is already running. Wait for it to finish or cancel it from the AI Summary menu.");
      return;
    }
    const { items, skipped } = this.targetItems(win);
    if (!items.length) {
      AISummary.alert(win, "Select one or more items (not standalone notes or attachments without a parent item).");
      return;
    }
    job.settings = AISummary.getSettings();
    const provider = job.settings.provider;
    if (!(await AISummary.ensureApiKey(win))) return;

    AISummary.batch.running = true;
    AISummary.batch.cancel = false;
    const pw = new Zotero.ProgressWindow({ closeOnClick: false });
    const label = job.question ? "Asking" : "Summarising";
    pw.changeHeadline("AI Summary – " + label + " with " + AISummary.getModel(provider));
    pw.show();

    const state = { remembered: null, total: items.length };
    const counts = { created: 0, replaced: 0, skipped: 0, failed: 0 };
    const errors = [];
    let suggestedModel = null;
    try {
      for (let i = 0; i < items.length; i++) {
        if (AISummary.batch.cancel) break;
        const item = items[i];
        const line = this.progressLine(pw, item);
        line.setProgress(20);
        try {
          const outcome = await this.processItem(win, item, job, state);
          counts[outcome]++;
          line.setProgress(100);
          if (outcome === "skipped") line.setText((item.getField("title") || "") + " (skipped)");
        } catch (e) {
          counts.failed++;
          errors.push((item.getField("title") || item.key) + ": " + e.message);
          if (e.suggestedModel) suggestedModel = e.suggestedModel;
          AISummary.log("Failed for " + item.key + ": " + (e.stack || e));
          line.setError();
        }
        if (i < items.length - 1 && job.settings.batchDelayMs) await AISummary.sleep(job.settings.batchDelayMs);
      }
    } finally {
      AISummary.batch.running = false;
    }

    const parts = [];
    if (counts.created) parts.push(counts.created + " created");
    if (counts.replaced) parts.push(counts.replaced + " replaced");
    if (counts.skipped) parts.push(counts.skipped + " skipped");
    if (counts.failed) parts.push(counts.failed + " failed");
    if (AISummary.batch.cancel) parts.push("cancelled");
    if (skipped) parts.push(skipped + " selected entries ignored");
    pw.addDescription(parts.join(", ") || "Nothing to do");
    pw.startCloseTimer(errors.length ? 15000 : 6000);

    if (errors.length) {
      AISummary.alert(win, "Some notes could not be created:\n\n" + errors.slice(0, 8).join("\n\n")
        + (errors.length > 8 ? "\n\n…and " + (errors.length - 8) + " more (see Help → Debug Output)." : ""));
      if (suggestedModel && Services.prompt.confirm(win, "AI Summary",
        AISummary.PROVIDER_LABELS[provider] + " suggests the model \u201C" + suggestedModel + "\u201D.\n\nSwitch to it?")) {
        AISummary.setPref("model." + provider, suggestedModel);
      }
    }
  },

  summarise(win, presetId) {
    const preset = AISummary.getPreset(presetId);
    return this.run(win, { preset });
  },

  ask(win) {
    const input = { value: "" };
    const ok = Services.prompt.prompt(
      win, "Ask AI about the selected item(s)",
      "Your question (the answer is saved as a note under each selected item):",
      input, null, { value: false }
    );
    const question = (input.value || "").trim();
    if (!ok || !question) return null;
    return this.run(win, { question, preset: AISummary.getPreset() });
  }
};
